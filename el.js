l10n.pluralize.el = function (n) {
  return n === 1 ? "one" : "other";
};

l10n.date.el = function (d) {
  var months = [
    "Ιαν",
    "Φεβ",
    "Μαρ",
    "Απρ",
    "Μαϊ",
    "Ιουν",
    "Ιουλ",
    "Αυγ",
    "Σεπ",
    "Οκτ",
    "Νοε",
    "Δεκ",
  ];
  return "" + d.getDate() + " " + months[d.getMonth()] + " " + d.getFullYear();
};
