l10n.date.hy = function(d) {
  var months = ['Հնվ', 'Փետ', 'Մար', 'Ապր', 'Մայ', 'Հուն',
                'Հուլ', 'Օգս', 'Սեպ', 'Հոկ', 'Նոյ', 'Դեկ'];
  return "" + d.getDate() + " " + months[d.getMonth()] + " " + d.getFullYear();
};